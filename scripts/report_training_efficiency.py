"""Generate docs/reports/training_efficiency.md (+ bar chart) from a measured ladder JSON.

    python scripts/report_training_efficiency.py --ladder results/profiles/ladder.json

Every number in the report comes from the JSON; nothing is typed by hand. Speed-ups are relative
to rung 0 (fp32, eager, num_workers=0). Loss parity is shown against the seed-to-seed spread of
the reference rung when ``--noise-seeds`` was used.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import typer

INK, INK2, SURFACE, BAR = "#0b0b0b", "#52514e", "#fcfcfb", "#2a78d6"


def _fmt(v: float | None, spec: str) -> str:
    return "—" if v is None else format(v, spec)


def main(
    ladder: Path = Path("results/profiles/ladder.json"),
    out_md: Path = Path("docs/reports/training_efficiency.md"),
    out_png: Path = Path("docs/reports/training_efficiency_tokens.png"),
) -> None:
    lad = json.loads(ladder.read_text())
    rows = [r for r in lad["results"] if "tokens_per_s" in r]
    if not rows:
        raise typer.BadParameter("ladder has no successful rungs")
    base = rows[0]["tokens_per_s"]
    hw = lad.get("hardware", {})
    gpu = ", ".join(hw.get("gpus", [])) or hw.get("cpu", "cpu")

    names = [r["rung"]["name"] for r in rows]
    vals = [r["tokens_per_s"] for r in rows]
    fig, ax = plt.subplots(figsize=(8, 3.6), facecolor=SURFACE)
    ax.set_facecolor(SURFACE)
    bars = ax.bar(names, vals, color=BAR, width=0.6, edgecolor=SURFACE, linewidth=2)
    for b, v in zip(bars, vals, strict=True):
        ax.text(b.get_x() + b.get_width() / 2, v, f"{v / base:.1f}×", ha="center", va="bottom",
                fontsize=9, color=INK)  # fmt: skip
    ax.set_title(f"Tokens/s per rung — {lad['model']} on {gpu} (labels: speed-up vs {names[0]})", color=INK,
                 fontsize=10, loc="left")  # fmt: skip
    ax.set_ylabel("tokens / s", color=INK2, fontsize=9)
    ax.tick_params(colors=INK2, labelsize=8)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color("#d4d3cf")
    ax.yaxis.grid(True, color="#ecebe8", linewidth=0.8)
    ax.set_axisbelow(True)
    plt.setp(ax.get_xticklabels(), rotation=20, ha="right")
    fig.tight_layout()
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=150)

    noise = lad.get("reference_loss_other_seeds") or []
    ref_loss = rows[0]["final_loss_mean"]
    spread = max(abs(n - ref_loss) for n in noise) if noise else None
    lines = [
        "# Training efficiency (generated)",
        "",
        f"Source: `{ladder}` · model `{lad['model']}` · hardware: {gpu} · AMP dtype `{lad['amp']}` · "
        f"git `{hw.get('git', '?')}`. Generated by `scripts/report_training_efficiency.py`.",
        "",
        f"![tokens/s per rung]({out_png.name})",
        "",
        "| Rung | tokens/s | speed-up | MFU | step ms | data wait | peak mem GB | compile s | loss (last ¼) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['rung']['name']} | {r['tokens_per_s']:,.0f} | {r['tokens_per_s'] / base:.2f}× | "
            f"{_fmt(r.get('mfu') and 100 * r['mfu'], '.1f')}{'%' if r.get('mfu') else ''} | "
            f"{r['step_ms']:.1f} | {100 * r.get('data_wait_frac', 0):.1f}% | "
            f"{_fmt(r.get('peak_mem_gb'), '.2f')} | {r['compile_s']:.1f} | {r['final_loss_mean']:.4f} |"
        )
    for r in lad["results"]:
        if "error" in r:
            lines.append(f"| {r['rung']['name']} | failed: {r['error'][:60]} | | | | | | | |")
    lines += ["", "## Loss parity", ""]
    if spread is not None:
        worst = max(abs(r["final_loss_mean"] - ref_loss) for r in rows)
        verdict = "within" if worst <= spread else "OUTSIDE"
        lines.append(f"Reference-rung loss spread across {len(noise)} other seeds: ±{spread:.4f}. "
                     f"Largest deviation of any rung from the reference: {worst:.4f} → {verdict} "
                     "seed noise.")  # fmt: skip
    else:
        lines.append("No noise seeds were run, so parity can't be judged against seed noise.")
    lines += ["", "Compile time is meaningful only for the first compiled rung; later rungs in the "
              "same process reuse the compilation cache."]  # fmt: skip
    out_md.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_md} and {out_png}")


if __name__ == "__main__":
    typer.run(main)
